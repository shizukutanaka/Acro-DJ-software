def get_translator(language_code: str) -> dict:
    """
    Get translation dictionary for specified language.

    Args:
        language_code: Language code (e.g., 'EN', 'JP', 'ZH')

    Returns:
        Dictionary mapping UI keys to translated strings
    """
    # Default to English if language not found
    return TRANSLATIONS.get(language_code, TRANSLATIONS.get('EN', {}))


def get_supported_languages() -> list:
    """
    Get list of all supported language codes.

    Returns:
        List of language codes in TRANSLATIONS
    """
    return sorted(list(TRANSLATIONS.keys()))


